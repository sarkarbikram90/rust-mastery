// Rust programming language
// Anatomy of a rust programming language
// fn is the keyword to define a function in rust
// println! is a macro in rust
// let is the keyword to define an immutable variable in rust
// {} is used as a placeholder for variables in rust
// ; is used to end a statement in rust
// rust is a compiled language
// cargo run compiles and runs the program
// cargo doc generates documentation for the program


fn main() {
    println!("Hello, world!");
 // let is for immutable variable, meaning the varibale value cannot be changed later   

    let day = "Monday";
    println!("Day: {}", day);

    let num = 2026;
    println!("Number: {}", num);
    
}
